typedef struct ADT7475State {
    SMBusDevice parent;

    /* registers */
    uint8_t regs[ADT7475_NUM_REG];

    /* ix2 transaction state */
    uint8_t command;

    /* internal state */
    uint16_t fan_speed_rating;
    uint8_t fan_speed_min;
    bool overtemperature_occured[ADT7475_NUM_TEMPS];
} ADT7475State;

