#define ADT7475_NUM_FANS    4

/* PWM Configuration BHVR values */
enum {
    BHVR_REMOTE_1_AUTO,
    BHVR_LOCAL_AUTO,
    BHVR_REMOTE_2_AUTO,
    BHVR_FULL_SPEED,
    BHVR_DISABLED,
    BHVR_FASTEST_LOCAL_2,
    BHVR_FASTEST_TEMP,
    BHVR_MANUAL_MODE,
};

